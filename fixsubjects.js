function fixSubjects(subjects, subjdict) {
  const levenshtein = (a, b) => {
    const matrix = Array.from({ length: a.length + 1 }, () =>
      Array(b.length + 1).fill(0)
    );
    for (let i = 0; i <= a.length; i++) matrix[i][0] = i;
    for (let j = 0; j <= b.length; j++) matrix[0][j] = j;
    for (let i = 1; i <= a.length; i++) {
      for (let j = 1; j <= b.length; j++) {
        matrix[i][j] =
          a[i - 1] === b[j - 1]
            ? matrix[i - 1][j - 1]
            : 1 + Math.min(matrix[i - 1][j], matrix[i][j - 1], matrix[i - 1][j - 1]);
      }
    }
    return matrix[a.length][b.length];
  };

  const subjdictKeys = Object.keys(subjdict);

  for (const branch in subjects) {
    for (const sub in subjects[branch]) {
      if (!subjdict.hasOwnProperty(sub)) {
        // Find closest key
        let minDist = Infinity;
        let closest = null;
        for (const k of subjdictKeys) {
          const dist = levenshtein(sub, k);
          if (dist < minDist) {
            minDist = dist;
            closest = k;
          }
        }
        if (minDist <= 2 && closest) {
          // Change to closest
          subjdict[sub] = subjdict[closest];
        } else {
          // Add new key
          subjdict[sub] = sub;
        }
      }
    }
  }
}

